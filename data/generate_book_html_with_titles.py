def build_pages(chapter_threads: List[str],
                threads_by_id: Dict[str, Dict[str, Any]],
                tweets_by_id: Dict[str, Dict[str, Any]],
                title_overrides: Dict[str, str]) -> List[Page]:

    cover = Page(href="index.html", title="Cover", kind="cover")
    titlep = Page(href="chapters/title.html", title=TITLEPAGE_TITLE, kind="title")
    toc = Page(href="toc.html", title="Table of Contents", kind="toc")
    preface = Page(href="chapters/preface.html", title=PREFACE_TITLE, kind="preface")
    singletons = Page(href="chapters/compendium.html", title=SINGLETONS_TITLE, kind="singletons", chapter_no=1)

    pages: List[Page] = [cover, titlep, toc, preface, singletons]

    sortable: List[Tuple[datetime, Page]] = []
    for tid in chapter_threads:
        thread = threads_by_id.get(str(tid))
        if not thread or not thread.get("tweets"):
            continue
        root = thread["tweets"][0]
        rid = str(root.get("id_str") or "")
        raw = (tweets_by_id.get(rid) or {}).get("raw") or root.get("raw") or {}
        dt = parse_created_at(root.get("created_at") or raw.get("created_at") or "") or datetime(3000, 1, 1, tzinfo=timezone.utc)

        title = title_overrides[str(tid)]
        p = Page(href=f"chapters/chapter_{tid}.html", title=title, kind="thread")
        p.subtitle = format_long_date(dt)
        sortable.append((dt, p))

    sortable.sort(key=lambda x: x[0])

    ch_no = 2
    for _, p in sortable:
        p.chapter_no = ch_no
        pages.append(p)
        ch_no += 1

    return pages


def write_cover(pages: List[Page]):
    idx = next((i for i, p in enumerate(pages) if p.kind == "cover"), None)
    prevp = pages[idx - 1] if idx is not None and idx > 0 else None
