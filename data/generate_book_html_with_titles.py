def load_selection(path: Path) -> Tuple[List[str], List[str]]:
    data = json.loads(path.read_text(encoding="utf-8"))

    # Your selection format has evolved. Support common cases.
    if isinstance(data, dict):
        if isinstance(data.get("chapter_threads"), list):
            chapter_threads = [str(x) for x in data["chapter_threads"]]
            comp = data.get("compendium_tweets") or []
            return chapter_threads, [str(x) for x in comp]
        if isinstance(data.get("threads"), list):
            chapter_threads = [str(x) for x in data["threads"]]
            comp = data.get("compendium_tweets") or []
            return chapter_threads, [str(x) for x in comp]

    if isinstance(data, list):
        # assume list of thread ids
        return [str(x) for x in data], []

    raise SystemExit(f"Unrecognized selection format in {path}")


def load_threads(path: Path) -> Dict[str, Dict[str, Any]]:
    threads = {}
    for obj in iter_jsonl(path):
        tid = str(obj.get("thread_id") or obj.get("id") or obj.get("threadId") or "")
        if not tid:
            continue
        threads[tid] = obj
    return threads


def load_tweets_raw(path: Path) -> Dict[str, Dict[str, Any]]:
    tweets = {}
    for obj in iter_jsonl(path):
        rid = str(obj.get("id_str") or obj.get("id") or "")
        if not rid:
            continue
        tweets[rid] = obj
    return tweets


def load_chapter_title_overrides(path: Path) -> Dict[str, str]:
    data = json.loads(path.read_text(encoding="utf-8"))
    chapters = data.get("chapters") if isinstance(data, dict) else None
    if not isinstance(chapters, list):
        raise SystemExit(f"Unexpected chapter_titles format in {path} (expected {{chapters:[...]}})")

    overrides: Dict[str, str] = {}
    for c in chapters:
        tid = c.get("thread_id")
        if not tid:
            continue
        title = (c.get("override_title") or "").strip()
        if not title:
            # Requirement: now use override titles in all cases (you said you filled all)
            raise SystemExit(f"Missing override_title for thread_id {tid} in {path}")
        overrides[str(tid)] = title
    return overrides


def nav_bar(prev_page: Optional[Page], next_page: Optional[Page], base_prefix: str) -> str:
    def label(p: Page) -> str:
        t = escape(p.title)
        if p.chapter_no is not None:
            t = f"{p.chapter_no}. {t}"
        return t

    if prev_page:
        left = f'<a class="nav-link nav-prev" href="{base_prefix}{escape(prev_page.href)}"><span class="nav-arrow">&larr;</span><span class="nav-label">{label(prev_page)}</span></a>'
    else:
        left = '<span class="nav-link nav-prev disabled"><span class="nav-arrow">&larr;</span></span>'

    center = f'<a class="nav-link nav-toc" href="{base_prefix}toc.html">Table of Contents</a>'

    if next_page:
        right = f'<a class="nav-link nav-next" href="{base_prefix}{escape(next_page.href)}"><span class="nav-label">{label(next_page)}</span><span class="nav-arrow">&rarr;</span></a>'
    else:
        right = '<span class="nav-link nav-next disabled"><span class="nav-arrow">&rarr;</span></span>'

    return (
        '<nav class="book-nav">'
        f'<div class="nav-left">{left}</div>'
        f'<div class="nav-center">{center}</div>'
        f'<div class="nav-right">{right}</div>'
        '</nav>'
    )


def floating_nav(prev_page: Optional[Page], next_page: Optional[Page], base_prefix: str) -> str:
    toc_href = f"{base_prefix}toc.html"
    parts = []
    if prev_page:
        parts.append(
            f'<a class="float-nav float-nav-prev" href="{base_prefix}{escape(prev_page.href)}" title="Previous chapter">'
            f'<span class="float-nav-chevron">&lsaquo;</span>'
            f'<span class="float-nav-label">Ch. &minus;</span>'
            f'</a>'
        )
    right_parts = []
    right_parts.append(
        f'<a class="float-nav-btn float-nav-toc" href="{escape(toc_href)}" title="Table of Contents">'
        f'<span class="float-nav-chevron">&and;</span>'
        f'<span class="float-nav-label">ToC</span>'
        f'</a>'
    )
    if next_page:
        right_parts.append(
            f'<a class="float-nav-btn float-nav-next" href="{base_prefix}{escape(next_page.href)}" title="Next chapter">'
            f'<span class="float-nav-chevron">&rsaquo;</span>'
            f'<span class="float-nav-label">Ch. +</span>'
            f'</a>'
        )
    parts.append(f'<div class="float-nav-right">{"".join(right_parts)}</div>')
    return "\n".join(parts)


