def iter_jsonl(path: Path):
    with path.open("r", encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if not line:
                continue
            yield json.loads(line)


def parse_created_at(s: str) -> Optional[datetime]:
    # Twitter created_at format: "Wed Oct 10 20:19:24 +0000 2018"
    if not s:
        return None
    try:
        # try strict twitter format
        return datetime.strptime(s, "%a %b %d %H:%M:%S %z %Y")
    except Exception:
        pass
    # fallback: ISO-ish
    try:
        dt = datetime.fromisoformat(s.replace("Z", "+00:00"))
        if dt.tzinfo is None:
            dt = dt.replace(tzinfo=timezone.utc)
        return dt
    except Exception:
        return None


def format_long_date(dt: datetime) -> str:
    return dt.astimezone(timezone.utc).strftime("%B %-d, %Y") if os.name != "nt" else dt.astimezone(timezone.utc).strftime("%B %#d, %Y")


